    # Create a dummy NodeScaler instance
    class DummyNodeScaler:
        def __init__(self, n_nodes, fill_value):
            self.n_nodes = n_nodes
            self.fill_value = fill_value
            # Use simpler mean/std for testing inverse transform logic
            self.mean_ = np.random.rand(n_nodes) * 10 
            self.std_ = np.random.rand(n_nodes) * 2 + 0.5 # Avoid std near zero
            if fill_value is not None:
                 # For testing, assume some nodes might be entirely fill_value
                 self.mean_[0] = 0 # Scaler would handle this
                 self.std_[0] = 1

        def transform(self, data):
            original_shape = data.shape
            data_reshaped = data.reshape(-1, self.n_nodes)
            transformed = np.zeros_like(data_reshaped)
            for i in range(self.n_nodes):
                col = data_reshaped[:, i]
                if self.fill_value is not None:
                    mask = (col == self.fill_value)
                    transformed[~mask, i] = (col[~mask] - self.mean_[i]) / self.std_[i]
                    transformed[mask, i] = self.fill_value
                else:
                    transformed[:, i] = (col - self.mean_[i]) / self.std_[i]
            return transformed.reshape(original_shape)

        def inverse_transform(self, data):
            original_shape = data.shape
            data_reshaped = data.reshape(-1, self.n_nodes)
            inverted = np.zeros_like(data_reshaped)
            for i in range(self.n_nodes):
                col = data_reshaped[:, i]
                if self.fill_value is not None:
                    mask = (col == self.fill_value)
                    inverted[~mask, i] = (col[~mask] * self.std_[i]) + self.mean_[i]
                    inverted[mask, i] = self.fill_value
                else:
                    inverted[:, i] = (col * self.std_[i]) + self.mean_[i]
            return inverted.reshape(original_shape)

